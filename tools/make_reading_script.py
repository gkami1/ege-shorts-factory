NOM_FRAMES = ["Ответ: {}.", "Получается {}.", "Итого {}.", "Это {}.", "В итоге выходит {}."]
CASE_FRAMES = [
    ("dative", "Это равно {}."),
    ("dative", "Прибавим к {} ещё немного."),
    ("genitive", "Вычтем из {} половину."),
    ("genitive", "Больше {} здесь получиться не может."),
    ("accusative", "Умножим на {} обе части."),
    ("accusative", "Разделим всё на {}."),
    ("instrumental", "Сравним это с {}."),
    ("prepositional", "Остановимся на {}."),
]
UNIT_FRAMES = ["Ответ: {}.", "В итоге {}.", "Получаем {}.", "Это примерно {}."]
UNIT_PICK = ["м/с", "м/с²", "км/ч", "м", "см", "с", "мин", "ч", "кг", "г", "Н", "Дж", "кДж", "Вт", "Па",
             "кПа", "А", "В", "Ом", "Кл", "Гц", "К", "°", "%", "л"]

# numbers whose stress TTS gets wrong most: -десят, -сот, teens, 40/90/100 in oblique cases
HOT = [40, 50, 60, 70, 80, 90, 11, 12, 13, 14, 15, 16, 17, 18, 19, 100, 200, 300, 500, 800, 1000]


def numbers() -> list[int]:
    ns = list(range(0, 21)) + list(range(30, 101, 10)) + HOT * 2
    ns += [rng.choice([rng.randint(21, 99), rng.randint(101, 999), rng.randint(1000, 9999)]) for _ in range(60)]
    rng.shuffle(ns)
    return ns


def main() -> None:
    lines = [ln.strip() for ln in NARRATION.strip().splitlines() if ln.strip()]
    ns = numbers()
    for i, n in enumerate(ns[:120]):
        lines.append(NOM_FRAMES[i % len(NOM_FRAMES)].format(spell_number(str(n))[0]))
    for i in range(110):
        case, frame = CASE_FRAMES[i % len(CASE_FRAMES)]
        n = rng.choice(HOT + list(range(2, 21)) + [rng.randint(21, 999)])
        lines.append(frame.format(_n2w(n, case=case)))
    for i in range(50):
        num = rng.choice(["0,5", "1,5", "2,5", "0,25", "0,75", "3,2", "12,5", "-0,5", "-1,25", "0,04"])
        lines.append(NOM_FRAMES[i % len(NOM_FRAMES)].format(spell_number(num)[0]))
    for i in range(70):
        u = UNIT_PICK[i % len(UNIT_PICK)]
        n = str(rng.choice(HOT + list(range(1, 25)) + [rng.randint(25, 500)]))
        if u in UNITS:
            lines.append(UNIT_FRAMES[i % len(UNIT_FRAMES)].format(spell_with_unit(n, u)))
    out = Path(__file__).resolve().parents[1] / "assets" / "voices" / "script" / "reading_script.txt"
    out.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(f"{i + 1:03d}\t{ln[0].upper() + ln[1:]}" for i, ln in enumerate(lines)) + "\n"
    out.write_text(text, encoding="utf-8")
    words = sum(len(ln.split()) for ln in lines)
    print(f"{out}: {len(lines)} lines, {words} words, ~{words / 2.3 / 60:.0f} min at a calm pace")


if __name__ == "__main__":
    main()
